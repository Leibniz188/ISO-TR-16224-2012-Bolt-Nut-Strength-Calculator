"""
ISO/TR 16224:2012 bolt-nut tensile failure calculator V13
=========================================================

Outputs per case folder:
  1) <CASE_NAME>_drawing.pdf      -> drawing only (CAD-style geometry/dimensions)
  2) <CASE_NAME>_calculation.md   -> 中文公式、代入过程、结果和警告

Key user-requested behavior:
- Nut height m can be generated by ratio m = k_m * D (default k_m=0.8),
  or supplied as a custom value.
- Thread angle is user-defined.
- Profile truncation coefficients are user-defined.
- ISO/TR 16224 correction factors are only applied in the ranges explicitly
  given by the report. When a correction term is outside its stated range,
  that correction is ignored (factor = 1.0), and the MD report warns that
  accuracy/applicability is reduced and a larger safety factor should be
  considered by the designer.
- PDF contains drawings only; all calculation text/formulas are written to MD.

Units:
- length: mm
- stress: MPa = N/mm^2
- force: N (MD also reports kN)
"""

