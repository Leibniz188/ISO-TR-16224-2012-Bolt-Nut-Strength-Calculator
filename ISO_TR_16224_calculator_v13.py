def external_root_fillet_geometry(g):
    """
    根据用户输入的牙型角和 h_external_root 构造与两侧理论牙面相切的圆弧。

    设 t = alpha/2，h_r = h_external_root：
        rho = h_r*sin(t)/(1-sin(t))

    对 alpha=60° 且 h_r=H/6，有 rho=H/6。
    """
    t = math.radians(thread_angle / 2.0)
    sin_t = math.sin(t)
    cos_t = math.cos(t)

    if sin_t <= 0.0 or sin_t >= 1.0:
        raise ValueError("无法为当前 thread_angle 构造有限的外螺纹牙底相切圆弧")

    h_r = g["h_external_root"]
    rho = h_r * sin_t / (1.0 - sin_t)

    theoretical_root_depth = g["H"] - g["h_flat"]
    bottom_depth = theoretical_root_depth - h_r
    center_depth = bottom_depth - rho

    x_tangent = rho * cos_t
    tangent_depth = center_depth + rho * sin_t

    return {
        "rho": rho,
        "theoretical_root_depth": theoretical_root_depth,
        "bottom_depth": bottom_depth,
        "center_depth": center_depth,
        "x_tangent": x_tangent,
        "tangent_depth": tangent_depth,
    }


def draw_external_root_arc(c, x_mid, y_of_depth, scale, fillet):
    """绘制真实圆弧；最低点位于 d3 深度，且与两侧牙面相切。"""
    rho_p = fillet["rho"] * scale
    center_y = y_of_depth(fillet["center_depth"])

    x1 = x_mid - rho_p
    y1 = center_y - rho_p
    x2 = x_mid + rho_p
    y2 = center_y + rho_p

    t_deg = thread_angle / 2.0
    start_angle = 180.0 + t_deg
    extent = 180.0 - thread_angle

    c.saveState()
    c.setLineWidth(LW_OBJECT)
    c.arc(x1, y1, x2, y2, startAng=start_angle, extent=extent)
    c.restoreState()


def hatch_rect(c, x, y, w, h, spacing=7, angle=45):
    c.saveState()
    path = c.beginPath()
    path.rect(x, y, w, h)
    c.clipPath(path, stroke=0, fill=0)
    c.setLineWidth(LW_HATCH)
    # 45-degree hatch family; enough for technical section indication.
    span = w + h + 100
    start = x - h - 50
    t = start
    while t < x + w + 50:
        c.line(t, y-20, t+h+60, y+h+40)
        t += spacing
    c.restoreState()



def hatch_polygon(c, points, spacing=8):
    """Clip hatch lines to a polygon for a cleaner sectional CAD appearance."""
    c.saveState()
    p = c.beginPath()
    p.moveTo(points[0][0], points[0][1])
    for x, y in points[1:]:
        p.lineTo(x, y)
    p.close()
    c.clipPath(p, stroke=0, fill=0)
    c.setLineWidth(LW_HATCH)
    xs = [q[0] for q in points]
    ys = [q[1] for q in points]
    xmin, xmax = min(xs), max(xs)
    ymin, ymax = min(ys), max(ys)
    span = (xmax-xmin) + (ymax-ymin) + 60
    t = xmin - (ymax-ymin) - 40
    while t < xmax + 40:
        c.line(t, ymin-20, t+span, ymin-20+span)
        t += spacing
    c.restoreState()

