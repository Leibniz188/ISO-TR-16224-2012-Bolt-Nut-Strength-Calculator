# Labels only; no material/thread database is used.
bolt_property_class = "10.9"
nut_property_class = "10"

# Safety factor (engineering post-processing, not an original ISO/TR load formula)
safety_factor = 2

# Material tensile strengths
Rm = 1000.0       # bolt tensile strength, MPa
Rmn = 800.0       # nut/internal-thread material tensile strength, MPa

# Thread main geometry
d = 60.0              # nominal major diameter d (= D for mating thread), mm
P = 3.0               # pitch, mm
thread_angle = 60.0   # included thread angle, deg; not forced to 60

# Thread-profile truncation coefficients, relative to H
k_flat = 1.0 / 8.0            # flat truncation height = k_flat * H
k_external_root = 1.0 / 6.0   # external root equivalent truncation = coeff * H
k_internal_crest = 1.0 / 4.0  # internal crest truncation = coeff * H

# Nut width across flats
s = 90.0          # mm

# Nut height mode:
#   "ratio"  -> m = nut_height_ratio * D; default common design value = 0.8D
#   "custom" -> m = nut_height_custom
nut_height_mode = "ratio"
nut_height_ratio = 0.80
nut_height_custom = 30.0   # mm; used only when nut_height_mode == "custom"

# Chamfer geometry
hc = 2.0          # chamfer height per end, mm
chamfer_ends = 2  # 1 = one-end chamfer, 2 = both-end chamfer

# Drawing-only countersink/chamfer included angle; not used in strength formulas
drawing_countersink_included_angle = 90.0


# ============================================================================
# 3. INPUT VALIDATION AND GEOMETRY
# ============================================================================

def validate_inputs():
    if d <= 0 or P <= 0:
        raise ValueError("d and P must be > 0")
    if not (0 < thread_angle < 180):
        raise ValueError("thread_angle must satisfy 0 < angle < 180 deg")
    if Rm <= 0 or Rmn <= 0:
        raise ValueError("Rm and Rmn must be > 0")
    if safety_factor <= 0:
        raise ValueError("safety_factor must be > 0")
    if s <= 0:
        raise ValueError("s must be > 0")
    if hc < 0:
        raise ValueError("hc must be >= 0")
    if chamfer_ends not in (1, 2):
        raise ValueError("chamfer_ends must be 1 or 2")
    if nut_height_mode not in ("ratio", "custom"):
        raise ValueError('nut_height_mode must be "ratio" or "custom"')
    if nut_height_ratio <= 0:
        raise ValueError("nut_height_ratio must be > 0")
    if nut_height_custom <= 0:
        raise ValueError("nut_height_custom must be > 0")

    for name, value in (
        ("k_flat", k_flat),
        ("k_external_root", k_external_root),
        ("k_internal_crest", k_internal_crest),
    ):
        if not (0.0 <= value < 1.0):
            raise ValueError(f"{name} must satisfy 0 <= {name} < 1")

    if k_flat + k_external_root >= 1.0:
        raise ValueError("k_flat + k_external_root must be < 1")
    if k_flat + k_internal_crest >= 1.0:
        raise ValueError("k_flat + k_internal_crest must be < 1")


def resolve_nut_height(D_value):
    if nut_height_mode == "ratio":
        return nut_height_ratio * D_value, (
            f"m = nut_height_ratio * D = {nut_height_ratio:.6f} * {D_value:.6f}"
        )
    return nut_height_custom, f"m = nut_height_custom = {nut_height_custom:.6f}"


def thread_dimensions():
    """Parametric symmetric V-thread geometry."""
    alpha2 = math.radians(thread_angle / 2.0)
    tan_half = math.tan(alpha2)
    H = P / (2.0 * tan_half)

    h_flat = k_flat * H
    h_external_root = k_external_root * H
    h_internal_crest = k_internal_crest * H

    d2 = d - 2.0 * (H / 2.0 - h_flat)
    D2 = d2

    d1 = d - 2.0 * (H - h_flat - h_internal_crest)
    D1 = d1

    d3 = d - 2.0 * (H - h_flat - h_external_root)

    if min(d1, d2, d3, D1, D2) <= 0:
        raise ValueError("Calculated thread diameter <= 0; check geometry inputs")

    return {
        "D": d,
        "d": d,
        "H": H,
        "tan_half": tan_half,
        "h_flat": h_flat,
        "h_external_root": h_external_root,
        "h_internal_crest": h_internal_crest,
        "d1": d1,
        "d2": d2,
        "d3": d3,
        "D1": D1,
        "D2": D2,
    }


def effective_nut_height(m_value):
    if chamfer_ends == 1:
        meff = m_value - 0.6 * hc
        formula = "meff = m - 0.6 hc"
    else:
        meff = m_value - 1.2 * hc
        formula = "meff = m - 1.2 hc"
    if meff <= 0:
        raise ValueError("meff <= 0; check m, hc and chamfer_ends")
    return meff, formula


