# 4. CALCULATION
# ============================================================================

def nominal_stress_area(d2_value, d3_value):
    return math.pi / 4.0 * ((d2_value + d3_value) / 2.0) ** 2


def actual_stress_area(d1_value, d2_value):
    # Confirmed in the user's manual review for this implementation.
    return math.pi / 4.0 * ((d1_value + d2_value) / 2.0) ** 2


def shear_areas(g, meff):
    tan_half = g["tan_half"]
    Dm = 1.026 * g["D1"]

    term1 = (
        (0.6 * meff / P)
        * math.pi
        * g["D1"]
        * (P / 2.0 + (g["d2"] - g["D1"]) * tan_half)
    )
    term2 = (
        (0.4 * meff / P)
        * math.pi
        * Dm
        * (P / 2.0 + (g["d2"] - Dm) * tan_half)
    )
    ASb = term1 + term2

    ASn = (
        (meff / P)
        * math.pi
        * g["d"]
        * (P / 2.0 + (g["d"] - g["D2"]) * tan_half)
    )

    if ASb <= 0 or ASn <= 0:
        raise ValueError("Calculated ASb/ASn <= 0; check thread geometry")

    return Dm, term1, term2, ASb, ASn


def correction_factors(Rs, D_value):
    """
    Range behavior requested by user:
    outside a stated ISO/TR range -> do not extrapolate; ignore that correction,
    i.e. set factor to 1.0 and issue a warning.
    """
    warnings = []
    status = {}
    ratio = s / D_value

    # C1
    if 1.4 <= ratio < 1.9:
        C1 = -(ratio ** 2) + 3.8 * ratio - 2.6
        status["C1"] = (True, f"1.4 <= s/D={ratio:.6f} < 1.9")
    else:
        C1 = 1.0
        msg = (
            f"C1 out of range: s/D={ratio:.6f}; stated range is 1.4 <= s/D < 1.9. "
            "C1 is ignored (set to 1.0)."
        )
        warnings.append(msg)
        status["C1"] = (False, msg)

    # C2
    if Rs <= 1.0:
        C2 = 0.897
        status["C2"] = (True, f"Rs={Rs:.6f} <= 1 -> C2=0.897")
    elif Rs < 2.2:
        C2 = (
            5.594
            - 13.682 * Rs
            + 14.107 * Rs ** 2
            - 6.057 * Rs ** 3
            + 0.9353 * Rs ** 4
        )
        status["C2"] = (True, f"1 < Rs={Rs:.6f} < 2.2 -> Eq.(6) polynomial")
    else:
        C2 = 1.0
        msg = (
            f"C2 out of range: Rs={Rs:.6f} >= 2.2; Eq.(6) gives no formula there. "
            "C2 is ignored (set to 1.0)."
        )
        warnings.append(msg)
        status["C2"] = (False, msg)

    # C3
    if Rs <= 0.4:
        C3 = 1.0
        msg = (
            f"C3 out of range: Rs={Rs:.6f} <= 0.4; Eq.(6) gives no formula there. "
            "C3 is ignored (set to 1.0)."
        )
        warnings.append(msg)
        status["C3"] = (False, msg)
    elif Rs < 1.0:
        C3 = 0.728 + 1.769 * Rs - 2.896 * Rs ** 2 + 1.296 * Rs ** 3
        status["C3"] = (True, f"0.4 < Rs={Rs:.6f} < 1 -> Eq.(6) polynomial")
    else:
        C3 = 0.897
        status["C3"] = (True, f"Rs={Rs:.6f} >= 1 -> C3=0.897")

    if warnings:
        warnings.append(
            "One or more correction terms are outside the stated ISO/TR applicability range. "
            "Model applicability/accuracy is reduced. Consider a larger safety factor and "
            "verification by test or a more appropriate design method."
        )

    return C1, C2, C3, ratio, status, warnings


def calculate():
    validate_inputs()
    g = thread_dimensions()
    m_value, m_formula = resolve_nut_height(g["D"])
    meff, meff_formula = effective_nut_height(m_value)

    As_nom = nominal_stress_area(g["d2"], g["d3"])
    As = actual_stress_area(g["d1"], g["d2"])
    FBb = Rm * As

    Dm, ASb_term1, ASb_term2, ASb, ASn = shear_areas(g, meff)
    Rs = (Rmn * ASn) / (Rm * ASb)

    C1, C2, C3, s_over_D, correction_status, warnings = correction_factors(Rs, g["D"])

    FSb = 0.6 * Rm * ASb * C1 * C2
    FSn = 0.6 * Rmn * ASn * C1 * C3

    loads = {
        "FBb bolt breaking": FBb,
        "FSb bolt-thread stripping": FSb,
        "FSn nut-thread stripping": FSn,
    }
    governing_mode = min(loads, key=loads.get)
    governing_load = loads[governing_mode]
    allowable_load = governing_load / safety_factor

    return {
        "g": g,
        "m": m_value,
        "m_formula": m_formula,
        "meff": meff,
        "meff_formula": meff_formula,
        "As_nom": As_nom,
        "As": As,
        "FBb": FBb,
        "Dm": Dm,
        "ASb_term1": ASb_term1,
        "ASb_term2": ASb_term2,
        "ASb": ASb,
        "ASn": ASn,
        "Rs": Rs,
        "C1": C1,
        "C2": C2,
        "C3": C3,
        "s_over_D": s_over_D,
        "correction_status": correction_status,
        "warnings": warnings,
        "FSb": FSb,
        "FSn": FSn,
        "governing_mode": governing_mode,
        "governing_load": governing_load,
        "allowable_load": allowable_load,
    }


