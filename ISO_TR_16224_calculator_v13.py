def arrow_head(c, x, y, angle, size=5.5):
    a = math.radians(24)
    x1 = x - size * math.cos(angle - a)
    y1 = y - size * math.sin(angle - a)
    x2 = x - size * math.cos(angle + a)
    y2 = y - size * math.sin(angle + a)
    p = c.beginPath()
    p.moveTo(x, y)
    p.lineTo(x1, y1)
    p.lineTo(x2, y2)
    p.close()
    c.drawPath(p, fill=1, stroke=0)


def dim_h(c, x1, x2, y_obj, y_dim, text, font_size=8):
    c.saveState()
    c.setLineWidth(LW_DIM)
    ext = 3.5
    c.line(x1, y_obj, x1, y_dim + (ext if y_dim >= y_obj else -ext))
    c.line(x2, y_obj, x2, y_dim + (ext if y_dim >= y_obj else -ext))
    c.line(x1, y_dim, x2, y_dim)
    arrow_head(c, x1, y_dim, 0)
    arrow_head(c, x2, y_dim, math.pi)
    c.setFont("Helvetica", font_size)
    tw = c.stringWidth(text, "Helvetica", font_size)
    gap = 4
    c.setFillColorRGB(1, 1, 1)
    c.rect((x1+x2-tw)/2-gap, y_dim-font_size*0.45, tw+2*gap, font_size*1.15, fill=1, stroke=0)
    c.setFillColorRGB(0, 0, 0)
    c.drawCentredString((x1+x2)/2, y_dim-font_size*0.3, text)
    c.restoreState()


