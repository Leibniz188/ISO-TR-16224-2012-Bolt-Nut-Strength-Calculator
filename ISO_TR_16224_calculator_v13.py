def draw_angle_dim(c, cx, cy, radius, angle_deg, text=None, apex_up=True, font_size=8):
    """
    Draw an included-angle arc that follows the user-input thread angle.
    """
    c.saveState()
    c.setLineWidth(LW_DIM)
    n = 32
    pts = []
    if apex_up:
        for i in range(n + 1):
            phi = math.radians(-angle_deg / 2.0 + angle_deg * i / n)
            x = cx + radius * math.sin(phi)
            y = cy - radius * math.cos(phi)
            pts.append((x, y))
    else:
        for i in range(n + 1):
            phi = math.radians(-angle_deg / 2.0 + angle_deg * i / n)
            x = cx + radius * math.sin(phi)
            y = cy + radius * math.cos(phi)
            pts.append((x, y))
    for a, b in zip(pts[:-1], pts[1:]):
        c.line(a[0], a[1], b[0], b[1])
    p0, p1 = pts[0], pts[1]
    pn1, pn = pts[-2], pts[-1]
    arrow_head(c, p0[0], p0[1], math.atan2(p0[1]-p1[1], p0[0]-p1[0]))
    arrow_head(c, pn[0], pn[1], math.atan2(pn[1]-pn1[1], pn[0]-pn1[0]))
    if text is None:
        text = f"{angle_deg:.1f}°"
    mid = pts[len(pts)//2]
    c.setFont("Helvetica", font_size)
    c.drawCentredString(mid[0], mid[1] + (9 if not apex_up else -9), text)
    c.restoreState()


